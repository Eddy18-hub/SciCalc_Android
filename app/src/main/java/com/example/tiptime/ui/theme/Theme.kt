/**
 * Tema de la calculadora.
 *
 * No usa colores dinámicos (Material You) a propósito: el efecto parallax y las teclas están
 * diseñados sobre una paleta propia, y así la app se ve igual en cualquier teléfono.
 */
@Composable
fun SciCalcTheme(
    darkTheme: Boolean,
    content: @Composable () -> Unit,
) {
    val colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme

    // El modo oscuro se puede elegir dentro de la app, independientemente del sistema, así que
    // hay que ajustar el color de los iconos de las barras del sistema manualmente.
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            val controller = WindowCompat.getInsetsController(window, view)
            controller.isAppearanceLightStatusBars = !darkTheme
            controller.isAppearanceLightNavigationBars = !darkTheme
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content,
    )
}
